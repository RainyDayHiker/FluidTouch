"""Draws the new UI's own icons and writes them as LVGL A8 images.

    python src/app/icons/make_icons.py

writes icons.cpp next to this file. The icons are alpha only and take the
colour of the button text, like the LVGL symbols they sit next to. Each is
drawn 8 times larger and scaled down, for smooth edges. Needs Pillow.
"""
import os
from PIL import Image, ImageDraw

S = 8  # supersampling


def canvas(w, h):
    img = Image.new("L", (w * S, h * S), 0)
    return img, ImageDraw.Draw(img)


def line(d, p, q, width):
    """A line with round ends, in icon pixels."""
    (x0, y0), (x1, y1) = p, q
    d.line([(x0 * S, y0 * S), (x1 * S, y1 * S)], fill=255, width=round(width * S))
    r = width * S / 2
    for x, y in (p, q):
        d.ellipse([x * S - r, y * S - r, x * S + r, y * S + r], fill=255)


def ring(d, cx, cy, rx, ry, width, fill=255):
    d.ellipse([(cx - rx) * S, (cy - ry) * S, (cx + rx) * S, (cy + ry) * S], outline=fill,
              width=round(width * S))


def zero():
    """A slashed zero: the work origin. Solid, like the home symbol."""
    w, h = 18, 22
    img, d = canvas(w, h)
    ring(d, w / 2, h / 2, w / 2 - 0.5, h / 2 - 0.5, 4)
    line(d, (w - 4.2, 3.6), (4.2, h - 3.6), 3.4)
    return "zero", w, h, img


def crosshair():
    """The laser's crosshair: a ring with four ticks and a dot."""
    w = h = 24
    img, d = canvas(w, h)
    c = w / 2
    ring(d, c, c, 8, 8, 2.6)
    for (dx, dy) in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        line(d, (c + dx * 4.5, c + dy * 4.5), (c + dx * 11, c + dy * 11), 2.6)
    d.ellipse([(c - 1.8) * S, (c - 1.8) * S, (c + 1.8) * S, (c + 1.8) * S], fill=255)
    return "crosshair", w, h, img


def bit():
    """An end mill, cutting end down: shank, then a fluted body."""
    w, h = 12, 24
    img, d = canvas(w, h)
    # Shank, a little narrower than the body
    d.rounded_rectangle([2 * S, 0, (w - 2) * S, 9 * S], radius=S, fill=255)
    # Body with a square end
    d.rounded_rectangle([1 * S, 10 * S, (w - 1) * S, h * S], radius=S, fill=255)
    # Flutes: slanted gaps across the body
    for y in (12, 16.5, 21):
        d.line([(0, (y + 2.5) * S), (w * S, (y - 1.5) * S)], fill=0, width=round(1.4 * S))
    return "bit", w, h, img


def emit(icons, path):
    out = [
        "// Generated by make_icons.py. Do not edit; change the script and run it again.",
        '#include "app/icons/icons.h"',
        "",
    ]
    for name, w, h, img in icons:
        small = img.resize((w, h), Image.BOX)
        data = small.tobytes()
        out.append(f"static const uint8_t {name}_data[] = {{")
        for row in range(h):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[row * w:(row + 1) * w]) + ",")
        out.append("};")
        out.append("")
        out.append(f"const lv_image_dsc_t ICON_{name.upper()} = {{")
        out.append("    .header = {")
        out.append("        .magic = LV_IMAGE_HEADER_MAGIC,")
        out.append("        .cf = LV_COLOR_FORMAT_A8,")
        out.append("        .flags = 0,")
        out.append(f"        .w = {w},")
        out.append(f"        .h = {h},")
        out.append(f"        .stride = {w},")
        out.append("    },")
        out.append(f"    .data_size = sizeof({name}_data),")
        out.append(f"    .data = {name}_data,")
        out.append("};")
        out.append("")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    emit([zero(), crosshair(), bit()], os.path.join(here, "icons.cpp"))
